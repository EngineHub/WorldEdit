package com.sk89q.worldedit.extent.clipboard.io;

import com.sk89q.worldedit.entity.Entity;
import com.sk89q.worldedit.extent.clipboard.Clipboard;
import com.sk89q.worldedit.math.BlockVector3;
import com.sk89q.worldedit.math.Vector3;
import com.sk89q.worldedit.world.block.BaseBlock;
import org.enginehub.linbus.tree.LinTagType;
import org.junit.jupiter.api.DisplayName;
import org.junit.jupiter.api.Test;
import org.junit.jupiter.api.Timeout;
import org.junit.jupiter.params.ParameterizedTest;
import org.junit.jupiter.params.provider.MethodSource;

import java.io.IOException;
import java.io.InputStream;
import java.util.OptionalInt;
import java.util.stream.Stream;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertNotNull;
import static org.junit.jupiter.api.Assertions.assertNull;

/**
 * Loads small stored schematics, so that a change to the readers that breaks files already in the wild shows up.
 *
 * <p>All four files describe the same 3x2x2 build with its minimum at (-10, 64, 5) and its origin at
 * (-12, 64, 6): stone at the minimum, a top-half west-facing oak stair next to it, a north-facing chest named
 * "Golden" above the stone's neighbour in Z, and an oak planks block in the far top corner. Everything else is air.
 * They were generated by a throwaway script (an NBT encoder with fixed gzip headers), not by WorldEdit, so a
 * change to the writers cannot silently change them.</p>
 */
@DisplayName("Stored schematic files")
@Timeout(60)
class GoldenSchematicTest extends SchematicTestBase {

    private static final BlockVector3 MIN = BlockVector3.at(-10, 64, 5);
    private static final BlockVector3 MAX = BlockVector3.at(-8, 65, 6);
    private static final BlockVector3 ORIGIN = BlockVector3.at(-12, 64, 6);

    record Golden(String file, BuiltInClipboardFormat format, OptionalInt dataVersion) {
        @Override
        public String toString() {
            return file;
        }
    }

    static Stream<Golden> goldens() {
        return Stream.of(
            new Golden("sponge_v1.schem", BuiltInClipboardFormat.SPONGE_V1_SCHEMATIC, OptionalInt.of(1631)),
            new Golden("sponge_v2.schem", BuiltInClipboardFormat.SPONGE_V2_SCHEMATIC, OptionalInt.of(4671)),
            new Golden("sponge_v3.schem", BuiltInClipboardFormat.SPONGE_V3_SCHEMATIC, OptionalInt.of(4671)),
            new Golden("mcedit.schematic", BuiltInClipboardFormat.MCEDIT_SCHEMATIC, OptionalInt.empty())
        );
    }

    static Stream<Golden> spongeGoldens() {
        return goldens().filter(g -> g.format() != BuiltInClipboardFormat.MCEDIT_SCHEMATIC);
    }

    static Stream<Golden> goldensWithBiomes() {
        return goldens().filter(g -> g.format() == BuiltInClipboardFormat.SPONGE_V2_SCHEMATIC
            || g.format() == BuiltInClipboardFormat.SPONGE_V3_SCHEMATIC);
    }

    private static BlockVector3 at(int x, int y, int z) {
        return MIN.add(x, y, z);
    }

    @ParameterizedTest(name = "{0}")
    @MethodSource("goldens")
    void regionAndOrigin(Golden golden) throws IOException {
        Clipboard clipboard = readResource(golden.format(), golden.file());

        assertEquals(MIN, clipboard.getMinimumPoint());
        assertEquals(MAX, clipboard.getMaximumPoint());
        assertEquals(ORIGIN, clipboard.getOrigin());
        assertEquals(12, clipboard.getRegion().getVolume());
    }

    @ParameterizedTest(name = "{0}")
    @MethodSource("spongeGoldens")
    void spongeBlocks(Golden golden) throws IOException {
        Clipboard clipboard = readResource(golden.format(), golden.file());

        for (BlockVector3 pos : clipboard.getRegion()) {
            String expected = switch (pos.subtract(MIN).toString()) {
                case "(0, 0, 0)" -> state("minecraft:stone").getAsString();
                case "(1, 0, 0)" -> state("minecraft:oak_stairs[facing=west,half=top]").getAsString();
                case "(0, 0, 1)" -> state("minecraft:chest[facing=north]").getAsString();
                case "(2, 1, 1)" -> state("minecraft:oak_planks").getAsString();
                default -> "minecraft:air";
            };
            assertEquals(expected, clipboard.getFullBlock(pos).toImmutableState().getAsString(), () -> "at " + pos);
        }
    }

    @ParameterizedTest(name = "{0}")
    @MethodSource("goldens")
    void blockEntity(Golden golden) throws IOException {
        Clipboard clipboard = readResource(golden.format(), golden.file());

        BaseBlock chest = clipboard.getFullBlock(at(0, 0, 1));
        assertNotNull(chest.getNbt(), "the chest keeps its block entity");
        assertEquals("Golden", chest.getNbt().getTag("CustomName", LinTagType.stringTag()).value());
        if (golden.format() != BuiltInClipboardFormat.MCEDIT_SCHEMATIC) {
            // The MCEdit reader leaves the file's relative x/y/z in place, the Sponge readers make them absolute
            assertEquals(MIN.x(), chest.getNbt().getTag("x", LinTagType.intTag()).valueAsInt());
            assertEquals(MIN.y(), chest.getNbt().getTag("y", LinTagType.intTag()).valueAsInt());
            assertEquals(MIN.z() + 1, chest.getNbt().getTag("z", LinTagType.intTag()).valueAsInt());
        }
        assertNull(clipboard.getFullBlock(at(0, 0, 0)).getNbt(), "plain blocks have no NBT");
    }

    @Test
    void mceditBlocksComeFromLegacyIds() throws IOException {
        Clipboard clipboard = readResource(BuiltInClipboardFormat.MCEDIT_SCHEMATIC, "mcedit.schematic");

        // Compared as strings: the legacy mapper is a process-wide singleton and may hold another test's block types
        assertEquals("minecraft:stone", clipboard.getFullBlock(at(0, 0, 0)).toImmutableState().getAsString());
        assertEquals(state("minecraft:oak_stairs[facing=east,half=top,shape=straight]").getAsString(),
            clipboard.getFullBlock(at(1, 0, 0)).toImmutableState().getAsString());
        assertEquals(state("minecraft:chest[facing=north,type=single]").getAsString(),
            clipboard.getFullBlock(at(0, 0, 1)).toImmutableState().getAsString());
        assertEquals(state("minecraft:wall_torch[facing=east]").getAsString(),
            clipboard.getFullBlock(at(2, 0, 1)).toImmutableState().getAsString());
        assertEquals("minecraft:oak_planks", clipboard.getFullBlock(at(2, 1, 1)).toImmutableState().getAsString());
        assertEquals("minecraft:air", clipboard.getFullBlock(at(2, 0, 0)).toImmutableState().getAsString());
    }

    @ParameterizedTest(name = "{0}")
    @MethodSource("goldensWithBiomes")
    void biomes(Golden golden) throws IOException {
        Clipboard clipboard = readResource(golden.format(), golden.file());

        // Version 2 stores one biome per column (z * 3 + x), version 3 one per block (y-major)
        int[] bottomLayer = {0, 1, 1, 0, 0, 1};
        int[] topLayer = golden.format() == BuiltInClipboardFormat.SPONGE_V2_SCHEMATIC
            ? bottomLayer : new int[] {1, 1, 0, 0, 0, 1};
        String[] names = {"minecraft:plains", "minecraft:desert"};
        for (int y = 0; y < 2; y++) {
            for (int z = 0; z < 2; z++) {
                for (int x = 0; x < 3; x++) {
                    int expected = (y == 0 ? bottomLayer : topLayer)[z * 3 + x];
                    final int fy = y;
                    final int fz = z;
                    final int fx = x;
                    assertEquals(names[expected], clipboard.getBiome(at(x, y, z)).id(),
                        () -> "biome at " + fx + "," + fy + "," + fz);
                }
            }
        }
    }

    @ParameterizedTest(name = "{0}")
    @MethodSource("goldens")
    void entity(Golden golden) throws IOException {
        Clipboard clipboard = readResource(golden.format(), golden.file());

        if (golden.format() == BuiltInClipboardFormat.SPONGE_V1_SCHEMATIC) {
            assertEquals(0, clipboard.getEntities().size(), "version 1 has no entities");
            return;
        }
        assertEquals(1, clipboard.getEntities().size());
        Entity entity = clipboard.getEntities().get(0);
        assertEquals("minecraft:armor_stand", entity.getState().getType().id());
        assertEquals(Vector3.at(-9.5, 64.0, 5.5), entity.getLocation().toVector());
        assertEquals(90f, entity.getLocation().getYaw());
        assertEquals(-15f, entity.getLocation().getPitch());
    }

    @ParameterizedTest(name = "{0}")
    @MethodSource("spongeGoldens")
    void entityKeepsItsData(Golden golden) throws IOException {
        if (golden.format() == BuiltInClipboardFormat.SPONGE_V1_SCHEMATIC) {
            return;
        }
        Clipboard clipboard = readResource(golden.format(), golden.file());

        assertEquals("Stand", clipboard.getEntities().get(0).getState().getNbt()
            .getTag("CustomName", LinTagType.stringTag()).value());
    }

    @ParameterizedTest(name = "{0}")
    @MethodSource("goldens")
    void dataVersionIsReported(Golden golden) throws IOException {
        try (InputStream in = open(golden.file()); ClipboardReader reader = golden.format().getReader(in)) {
            assertEquals(golden.dataVersion(), reader.getDataVersion());
        }
    }
}
